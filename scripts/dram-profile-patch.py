#!/usr/bin/env python3
"""Write a U-Boot patch that sets the primary DRAM timings of the Radxa
Cubie A5E defconfig from a profile in config/dram/<name>.conf.

The mainline defconfig (U-Boot 2026.04) has
  CONFIG_DRAM_SUNXI_TPR6/10/11/12 = 0x38000000 0x802f3333 0xc7c5c4c2 0x3533302f
which do not suit every board revision (docs/COMMUNITY-FINDINGS.md §1).
The patch is applied after 420 (alternative parameters), so a board whose
memory check fails with the profile still gets the fallback set.

usage: dram-profile-patch.py <profile.conf> <output.patch>
"""
import re
import sys

DEFAULT = {"TPR6": "0x38000000", "TPR10": "0x802f3333",
           "TPR11": "0xc7c5c4c2", "TPR12": "0x3533302f"}


def main():
    conf, out = sys.argv[1], sys.argv[2]
    vals = {}
    for line in open(conf):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        k, v = (x.strip() for x in line.split("=", 1))
        if k not in DEFAULT or not re.fullmatch(r"0x[0-9a-f]{8}", v):
            sys.exit("%s: bad line %r" % (conf, line))
        vals[k] = v
    if set(vals) != set(DEFAULT):
        sys.exit("%s: needs exactly %s" % (conf, " ".join(DEFAULT)))
    old = ["CONFIG_DRAM_SUNXI_%s=%s" % (k, DEFAULT[k]) for k in DEFAULT]
    new = ["CONFIG_DRAM_SUNXI_%s=%s" % (k, vals[k]) for k in DEFAULT]
    name = conf.rsplit("/", 1)[-1].rsplit(".", 1)[0]
    with open(out, "w") as f:
        f.write("From: cubie-a5e-openwrt <noreply@github.com>\n")
        f.write("Subject: configs: radxa-cubie-a5e: DRAM timings for %s\n\n" % name)
        f.write("Generated by scripts/dram-profile-patch.py from config/dram/%s.conf.\n\n---\n" % name)
        f.write("--- a/configs/radxa-cubie-a5e_defconfig\n")
        f.write("+++ b/configs/radxa-cubie-a5e_defconfig\n")
        f.write("@@ -10,6 +10,6 @@\n")
        f.write(" CONFIG_DRAM_SUNXI_TPR1=0x06060606\n")
        for l in old:
            f.write("-" + l + "\n")
        for l in new:
            f.write("+" + l + "\n")
        # first line added by 420 (alternative parameters): this patch
        # must come after it
        f.write(" # Alternative parameters, used when the built-in DRAM memory check fails\n")


if __name__ == "__main__":
    main()
